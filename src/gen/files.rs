/// What a generated file says of itself in its first lines.
const GENERATED_MARKERS: &[&str] = &[
    "CODE GENERATED",
    "DO NOT EDIT",
    "DO NOT MODIFY",
    "@GENERATED",
    "GENERATED FILE",
    "THIS FILE IS AUTOGENERATED",
    "THIS FILE WAS GENERATED",
    "THIS FILE IS GENERATED",
    "AUTO-GENERATED",
    "AUTO GENERATED",
    "AUTOMATICALLY GENERATED",
];

/// How much of a file's start is looked at for a generated marker.
const MARKER_BYTES: usize = 1000;

/// A file whose lines are this long on average is a minified bundle.
const MINIFIED_LINE: usize = 500;

/// A file larger than this is listed but never read whole: it's data, or
/// generated. Hand-written source files of more than a megabyte are rare,
/// but they're there, and links into them must check.
pub const MAX_READ: u64 = 8 * 1024 * 1024;

/// One file at the commit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct File {
    /// From the top of the repository.
    pub path: String,
    /// The hash git gives its content: what tells a file changed.
    pub blob: String,
    /// How many lines it has; 0 for a binary file or one too big to read.
    pub lines: u32,
    pub bytes: u64,
    /// Whether it's text: neither binary nor too big to read.
    pub text: bool,
    /// Whether it says it was generated, or is minified.
    pub generated: bool,
}

/// Every file a wiki is written about, by path.
#[derive(Debug, Clone, Default)]
pub struct Files {
    pub files: BTreeMap<String, File>,
    /// Every directory that holds one of them, without a `/` at its end.
    pub dirs: BTreeSet<String>,
}

impl Files {
    /// The files git has in the checkout at `root`, less those
    /// [`skipped`] and those `exclude`'s globs match.
    pub fn list(root: &Path, exclude: &[String]) -> Result<Files> {
        let out = Command::new("git")
            .arg("-C")
            .arg(root)
            .args(["-c", "core.quotePath=false", "ls-files", "-s", "-z"])
            .output()
            .context("couldn't run git")?;
        if !out.status.success() {
            bail!(
                "git ls-files failed: {}",
                crate::printable::line(String::from_utf8_lossy(&out.stderr).trim())
            );
        }
        let listed = String::from_utf8_lossy(&out.stdout);
        let mut files = Files::default();
        for entry in listed.split('\0').filter(|entry| !entry.is_empty()) {
            // `<mode> <blob> <stage>\t<path>`
            let Some((head, path)) = entry.split_once('\t') else {
                continue;
            };
            let mut head = head.split(' ');
            let mode = head.next().unwrap_or_default();
            let blob = head.next().unwrap_or_default();
            // A submodule is a commit, not a file; a link is no file to read.
            if mode == "160000" || mode == "120000" || skipped(path) || excluded(path, exclude) {
                continue;
            }
            let measured = measure(&root.join(path));
            files.add(File {
                path: path.to_string(),
                blob: blob.to_string(),
                lines: measured.lines,
                bytes: measured.bytes,
                text: measured.text,
                generated: measured.generated,
            });
        }
        Ok(files)
    }

    /// Adds `file`, and the directories it's in.
    pub fn add(&mut self, file: File) {
        let mut dir = file.path.as_str();
        while let Some((parent, _)) = dir.rsplit_once('/') {
            self.dirs.insert(parent.to_string());
            dir = parent;
        }
        self.files.insert(file.path.clone(), file);
    }

    pub fn get(&self, path: &str) -> Option<&File> {
        self.files.get(path)
    }

    pub fn is_dir(&self, path: &str) -> bool {
        self.dirs.contains(path.trim_end_matches('/'))
    }

    /// The source files: those every wiki must cover.
    pub fn sources(&self) -> impl Iterator<Item = &File> {
        self.files.values().filter(|file| is_source(file))
    }

    /// How many lines of source there are.
    pub fn source_lines(&self) -> u64 {
        self.sources().map(|file| u64::from(file.lines)).sum()
    }

    /// `path` as one of the paths a subsection covers: a file's as it is, a
    /// directory's ending with `/`; `None` when it's neither here. A `./`
    /// or `/` before it is taken off.
    pub fn entry(&self, path: &str) -> Option<String> {
        let path = path.trim().trim_start_matches("./").trim_start_matches('/');
        if self.files.contains_key(path) {
            return Some(path.to_string());
        }
        let dir = path.trim_end_matches('/');
        if dir.is_empty() || dir == "." {
            return Some(String::new());
        }
        self.is_dir(dir).then(|| format!("{dir}/"))
    }

    /// The files `entries` cover, each once, in order.
    pub fn covered<'a>(&'a self, entries: &[String]) -> Vec<&'a File> {
        self.files
            .values()
            .filter(|file| covers(entries, &file.path))
            .collect()
    }
}

/// Whether one of `entries`, files and directories ending with `/` (the
/// empty one being the whole repository), covers `path`.
pub fn covers(entries: &[String], path: &str) -> bool {
    entries.iter().any(|entry| {
        if entry.is_empty() {
            return true;
        }
        match entry.strip_suffix('/') {
            Some(dir) => path
                .strip_prefix(dir)
                .is_some_and(|rest| rest.starts_with('/')),
            None => entry == path,
        }
    })
}

/// What reading a file from the disk found.
struct Measured {
    lines: u32,
    bytes: u64,
    text: bool,
    generated: bool,
}

/// Its lines, its size, whether it's text and whether it was generated.
fn measure(path: &Path) -> Measured {
    let unread = |bytes| Measured {
        lines: 0,
        bytes,
        text: false,
        generated: false,
    };
    let Ok(meta) = fs::metadata(path) else {
        return unread(0);
    };
    let bytes = meta.len();
    if !meta.is_file() || bytes > MAX_READ {
        return unread(bytes);
    }
    let mut content = Vec::new();
    if fs::File::open(path)
        .and_then(|mut file| file.read_to_end(&mut content))
        .is_err()
    {
        return unread(bytes);
    }
    if content.iter().take(8000).any(|&byte| byte == 0) {
        return unread(bytes);
    }
    let mut lines = content.iter().filter(|&&byte| byte == b'\n').count() as u32;
    if content.last().is_some_and(|&byte| byte != b'\n') {
        lines += 1;
    }
    Measured {
        lines,
        bytes,
        text: true,
        generated: is_generated(&content, lines),
    }
}

/// Whether `content`, of `lines` lines, says it was generated in its first
/// lines, or is minified.
fn is_generated(content: &[u8], lines: u32) -> bool {
    let head = String::from_utf8_lossy(&content[..content.len().min(MARKER_BYTES)]).to_uppercase();
    GENERATED_MARKERS.iter().any(|marker| head.contains(marker))
        || content.len() / lines.max(1) as usize > MINIFIED_LINE
}

/// The extensions of the files a wiki must cover: code, in the languages
/// people write it in.
const SOURCE_EXTENSIONS: &[&str] = &[
    "rs", "go", "py", "pyi", "ts", "tsx", "js", "jsx", "mjs", "cjs", "java", "kt", "kts", "scala",
    "c", "h", "cc", "cpp", "cxx", "hpp", "hh", "m", "mm", "swift", "rb", "sh", "bash", "zsh",
    "fish", "lua", "php", "cs", "fs", "ex", "exs", "erl", "hs", "ml", "clj", "dart", "r", "jl",
    "zig", "nim", "sql", "proto", "vue", "svelte", "nix", "pl", "ps1",
];

/// Build files named for what they are, without an extension that says.
const SOURCE_NAMES: &[&str] = &[
    "Makefile",
    "makefile",
    "GNUmakefile",
    "Dockerfile",
    "CMakeLists.txt",
    "Justfile",
    "justfile",
    "Rakefile",
    "BUILD",
    "BUILD.bazel",
];

/// Whether `file` is source: text in a language people write, or a build
/// file, that wasn't generated. Docs, data and configuration may be written
/// about, but needn't be.
pub fn is_source(file: &File) -> bool {
    if !file.text || file.generated {
        return false;
    }
    let name = file.path.rsplit('/').next().unwrap_or(&file.path);
    if SOURCE_NAMES.contains(&name) {
        return true;
    }
    match name.rsplit_once('.') {
        Some((stem, extension)) if !stem.is_empty() => {
            SOURCE_EXTENSIONS.contains(&extension.to_ascii_lowercase().as_str())
        }
        _ => false,
    }
}

/// Whether `path` is one never written about: in a directory of
/// [`SKIP_DIRS`], with an extension of [`SKIP_EXTENSIONS`] (or a minified
/// one), or named in [`SKIP_FILES`].
pub fn skipped(path: &str) -> bool {
    let mut parts: Vec<&str> = path.split('/').collect();
    let name = parts.pop().unwrap_or_default();
    if parts.iter().any(|dir| SKIP_DIRS.contains(dir)) || SKIP_FILES.contains(&name) {
        return true;
    }
    let lower = name.to_ascii_lowercase();
    if lower.ends_with(".min.js") || lower.ends_with(".min.css") || lower.ends_with("-lock.json") {
        return true;
    }
    match lower.rsplit_once('.') {
        Some((stem, extension)) if !stem.is_empty() => SKIP_EXTENSIONS.contains(&extension),
        _ => false,
    }
}

/// Whether `path` is excluded by one of `exclude`'s globs.
pub fn excluded(path: &str, exclude: &[String]) -> bool {
    crate::glob::any(exclude, path)
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    /// A text file at `path` of ten lines, as a test's listing has it.
    pub fn file(path: &str) -> File {
        File {
            path: path.into(),
            blob: "b".into(),
            lines: 10,
            bytes: 100,
            text: true,
            generated: false,
        }
    }

    #[test]
    fn what_nobody_reads_to_understand_the_code_is_skipped() {
        for path in [
            "node_modules/x/index.js",
            "web/dist/app.js",
            "vendor/github.com/a/b.go",
            "Cargo.lock",
            "web/package-lock.json",
            "assets/logo.png",
            "static/app.min.js",
            "deploy/.env",
            "go.sum",
            "a/__pycache__/m.pyc",
        ] {
            assert!(skipped(path), "{path}");
        }
        for path in [
            "src/build/mod.rs",
            "src/lock.rs",
            "README.md",
            "web/src/app.ts",
            ".envrc",
        ] {
            assert!(!skipped(path), "{path}");
        }
    }

    #[test]
    fn a_generated_or_minified_file_says_so() {
        assert!(is_generated(
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
            2
        ));
        assert!(is_generated(b"# @generated by a tool\n", 1));
        assert!(is_generated(&[b'x'; 2000], 1));
        assert!(!is_generated(b"fn main() {}\n", 1));
    }

    #[test]
    fn what_a_subsection_covers_is_its_files_and_what_its_directories_hold() {
        let entries = vec!["src/tui/".to_string(), "src/main.rs".to_string()];
        assert!(covers(&entries, "src/tui/app.rs"));
        assert!(covers(&entries, "src/tui/app/commands.rs"));
        assert!(covers(&entries, "src/main.rs"));
        assert!(!covers(&entries, "src/tuition.rs"));
        assert!(!covers(&entries, "src/main.rs.bak"));
        assert!(covers(&[String::new()], "anything"));
    }

    #[test]
    fn source_is_code_and_build_files_not_docs_data_or_generated() {
        assert!(is_source(&file("src/a.rs")));
        assert!(is_source(&file("Makefile")));
        assert!(is_source(&file("scripts/install.sh")));
        assert!(!is_source(&file("README.md")));
        assert!(!is_source(&file("config.toml")));
        assert!(!is_source(&file(".rs")));
        let binary = File {
            text: false,
            ..file("a.rs")
        };
        assert!(!is_source(&binary));
        let generated = File {
            generated: true,
            ..file("api.pb.go")
        };
        assert!(!is_source(&generated));
    }

    #[test]
    fn an_entry_is_a_file_or_a_directory_that_is_there() {
        let mut files = Files::default();
        files.add(file("src/tui/app.rs"));
        files.add(file("src/main.rs"));
        assert_eq!(files.entry("./src/main.rs").as_deref(), Some("src/main.rs"));
        assert_eq!(files.entry("src/tui").as_deref(), Some("src/tui/"));
        assert_eq!(files.entry("/src/").as_deref(), Some("src/"));
        assert_eq!(files.entry("src/gone.rs"), None);
        assert_eq!(files.covered(&["src/tui/".into()]).len(), 1);
        assert_eq!(files.source_lines(), 20);
    }

    #[test]
    fn the_files_are_git_s_with_their_lines_less_what_is_skipped() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        let git = |args: &[&str]| {
            let out = Command::new("git")
                .arg("-C")
                .arg(root)
                .args(args)
                .output()
                .unwrap();
            assert!(out.status.success(), "{out:?}");
        };
        git(&["init", "-q"]);
        fs::create_dir_all(root.join("src")).unwrap();
        fs::write(root.join("src/a.rs"), "fn a() {}\nfn b() {}\n").unwrap();
        fs::write(root.join("src/gen.rs"), "x").unwrap();
        fs::write(
            root.join("src/api.pb.go"),
            "// Code generated. DO NOT EDIT.\n",
        )
        .unwrap();
        fs::write(root.join("Cargo.lock"), "lock").unwrap();
        fs::write(root.join("logo.png"), [0u8, 1, 2]).unwrap();
        fs::write(root.join("data.bin"), [0u8, 1, 2]).unwrap();
        fs::write(root.join("blob"), [0u8, 1, 2]).unwrap();
        git(&["add", "."]);
        let files = Files::list(root, &["src/gen.rs".into()]).unwrap();
        let paths: Vec<&str> = files.files.keys().map(String::as_str).collect();
        assert_eq!(paths, ["blob", "src/a.rs", "src/api.pb.go"]);
        let a = files.get("src/a.rs").unwrap();
        assert_eq!((a.lines, a.text, a.blob.len()), (2, true, 40));
        assert!(!files.get("blob").unwrap().text);
        assert!(files.get("src/api.pb.go").unwrap().generated);
        assert_eq!(files.sources().count(), 1);
    }
}
