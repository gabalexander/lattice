//! The files a wiki is written about: those git has at the commit, less
//! what nobody reads to understand the code, each with its lines and the
//! hash git gives its content. Which of them are source files, the ones
//! every wiki must cover; what a subsection's paths, files and
//! directories, cover; and the globs the `exclude` setting takes.
//!
//! git's own list is the start, so what `.gitignore` ignores was never
//! there. Left out besides, whatever the settings say: vendored and built
//! directories, lock files, binaries and media by their extension, and
//! files that hold credentials by their name. A file whose first lines say
//! it was generated, or whose lines are as long as a minified bundle's,
//! stays listed, for a link to it to check, but needn't be covered and
//! isn't read for what it defines; one bigger than [`MAX_READ`] is listed
//! as a binary is, unread.
//!
//! Adapted from crystal's wiki generator (`src/wiki/files.rs`, MIT), with
//! the filters of deepwiki-by-cc's `src/lib/server/pipeline/scanner.ts`
//! (MIT; see THIRD_PARTY_NOTICES.md).

